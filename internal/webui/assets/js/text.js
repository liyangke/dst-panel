// 别人写的文本进界面之前的处理。
//
// 面板里有一类内容不是我们自己产生的：房间名、标签、模组介绍，都是外部人填的自由文本。
// 直接原样丢给浏览器会撞两件事——控制字符（实测见过以 \x01 开头的房间名）在界面上是
// 看不见的洞，私有区字形（从聊天软件里粘进来的表情码，还有变音符）面板没有那套字体，
// 画出来是一排方框。
//
// 这里只删和压空白，从不替换成别的字：外部文本是它的作者留下的证据，
// 把它"修饰"成通顺的版本就不是那条内容了。
//
// 两类字符都换成一个空格再统一压扁，而不是直接删掉：删掉会把
// "A\u{F0008}B" 粘成 "AB"，而那个表情本来就是个分隔符，粘完的字符串是对方没写过的。
const INVISIBLE = /[\u0000-\u0008\u000e-\u001f\u007f-\u009f]/g;
// 平面 0 的私有区（E000–F8FF）、平面 1 的变音符与标签字符（E0000–E0FFF）、
// 平面 15/16 的私有区（F0000–10FFFF）。u 标志必须带：\u{F0000} 是码点不是代码单元。
const PRIVATE_USE = /[\u{e000}-\u{f8ff}\u{e0000}-\u{e0fff}\u{f0000}-\u{10ffff}]/gu;

// plain 去掉画不出来的字符并把连续空白压成一个空格。
// fallback 用于"清完什么都不剩"的那一条：返回空串的话界面上那一格就是空的，
// 读者分不清是对方真没写还是我们没显示，所以给它一个兜底说法。
export function plain(text, fallback) {
  const s = String(text === null || text === undefined ? "" : text)
    .replace(INVISIBLE, " ")
    .replace(PRIVATE_USE, " ")
    .replace(/\s+/g, " ")
    .trim();
  return s || (fallback || "");
}

// known 只在"这个词我们真的认识"时才把它显示出来。
// 后端把码值翻成中文时，认不出的一律原样回传（那是最诚实的做法）；
// 可界面上把一个原样回传的英文词摆在"季节"那一格，读起来就像在说"这间房是 fuck 季"。
// 所以这一格空着比搬上来好：空着是"没读到"，搬上来是一个假答案。
export function known(raw, label) {
  if (!raw || !label) return "";
  return label === raw ? "" : label;
}
